'use client';

import { useState } from 'react';

import {
  ActionForm,
  Button,
  Checkbox,
  FormActions,
  FormMessage,
  Input,
  SubmitButton,
  useFieldError,
} from '@/components/ui';
import type { ActionState } from '@/lib/action-state';

import { SecretReveal } from './secret-reveal';

export interface CreatedWebhookEndpoint {
  id: string;
  url: string;
  secret: string;
}

export interface EventOption {
  value: string;
  description: string;
}

function GroupError({ name }: { name: string }) {
  const error = useFieldError(name);
  return error ? (
    <p role="alert" className="text-xs font-medium text-danger">
      {error}
    </p>
  ) : null;
}

/**
 * Registers a webhook endpoint with the events it subscribes to. The signing secret is
 * generated by the server and displayed once, right after creation.
 */
export function WebhookEndpointForm({
  action,
  events,
  defaultEvents,
  disabled = false,
  httpsOnly,
}: {
  action: (
    previous: ActionState<CreatedWebhookEndpoint>,
    formData: FormData,
  ) => Promise<ActionState<CreatedWebhookEndpoint>>;
  events: readonly EventOption[];
  /** Events ticked on a fresh form (the ones this kind of partner usually wants). */
  defaultEvents: readonly string[];
  disabled?: boolean;
  /** Production only accepts public https:// URLs. */
  httpsOnly: boolean;
}) {
  const [generation, setGeneration] = useState(0);
  const defaults = (): ReadonlySet<string> => new Set(defaultEvents);
  // Controlled, so a failed submit never re-ticks events the partner had left out.
  const [selected, setSelected] = useState<ReadonlySet<string>>(defaults);
  const toggle = (value: string, checked: boolean) =>
    setSelected((current) => {
      const next = new Set(current);
      if (checked) next.add(value);
      else next.delete(value);
      return next;
    });
  return (
    <ActionForm key={generation} action={action} className="space-y-4" autoComplete="off">
      {(state) =>
        state.ok && state.data ? (
          <div className="space-y-4">
            <SecretReveal
              title="Endpoint created — copy its signing secret now"
              secret={state.data.secret}
              testId="webhook-secret"
            >
              Use it to verify the <code className="font-mono">x-birem-signature</code> header of
              every delivery to <span className="break-all font-medium">{state.data.url}</span>.
            </SecretReveal>
            <Button
              variant="secondary"
              size="sm"
              onClick={() => {
                setSelected(defaults());
                setGeneration((n) => n + 1);
              }}
            >
              I have stored it — add another endpoint
            </Button>
          </div>
        ) : (
          <>
            <Input
              name="url"
              type="url"
              label="Endpoint URL"
              placeholder="https://example.com/webhooks/bi-rem"
              hint={
                httpsOnly
                  ? 'A public https:// URL that answers 2xx within 3 seconds.'
                  : 'https:// in production. In development, http://localhost is accepted.'
              }
              required
              maxLength={500}
              disabled={disabled}
            />
            <Input
              name="description"
              label="Description"
              maxLength={200}
              disabled={disabled}
              hint="For your own reference."
            />
            <fieldset className="space-y-2.5" disabled={disabled}>
              <legend className="text-sm font-medium text-fg">
                Events
                <span aria-hidden="true" className="ml-0.5 text-danger">
                  *
                </span>
              </legend>
              <div className="grid gap-2.5 sm:grid-cols-2">
                {events.map((event) => (
                  <Checkbox
                    key={event.value}
                    name="events[]"
                    value={event.value}
                    label={<code className="font-mono text-[0.8125rem]">{event.value}</code>}
                    hint={event.description}
                    checked={selected.has(event.value)}
                    onChange={(e) => toggle(event.value, e.target.checked)}
                  />
                ))}
              </div>
              <GroupError name="events" />
            </fieldset>
            <FormMessage showSuccess={false} />
            <FormActions>
              <SubmitButton pendingLabel="Creating…" disabled={disabled || undefined}>
                Add endpoint
              </SubmitButton>
            </FormActions>
          </>
        )
      }
    </ActionForm>
  );
}
