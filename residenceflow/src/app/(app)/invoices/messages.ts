/** Translates the error / message of an ActionResult (service errors are keyed by their English text). */
export function translateResult<R>(r: ActionResult<R>, t: T): ActionResult<R> {
  if (!r.ok) return { ...r, error: t(r.error) };
  return r.message ? { ...r, message: t(r.message) } : r;
}

